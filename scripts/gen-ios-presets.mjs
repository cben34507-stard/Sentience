// Regenerates ios/Sentience/Models/LabPresets.swift from packages/shared so
// the iPhone app and the web app share one list of tests.
//   npm run build --workspace=packages/shared && node scripts/gen-ios-presets.mjs
import { writeFileSync } from "node:fs";
import { LAB_TESTS } from "../packages/shared/dist/index.js";

const q = (s) => JSON.stringify(s);
const num = (n) => (n == null ? "nil" : String(n));
const rows = LAB_TESTS.map(
  (t) =>
    `        .init(key: ${q(t.key)}, name: ${q(t.name)}, panel: ${q(t.panel)}, unit: ${q(t.unit)}, refLow: ${num(t.refLow)}, refHigh: ${num(t.refHigh)}, healthKitType: ${t.healthKit ? q(t.healthKit.type) : "nil"}, healthKitUnit: ${t.healthKit ? q(t.healthKit.unit) : "nil"}),`,
).join("\n");

const out = `// Generated by scripts/gen-ios-presets.mjs from packages/shared. Do not edit by hand.
import Foundation

struct LabPreset: Identifiable, Hashable {
    let key: String
    let name: String
    let panel: String
    let unit: String
    let refLow: Double?
    let refHigh: Double?
    /// HealthKit quantity type this result is written to, if Apple Health has one.
    let healthKitType: String?
    let healthKitUnit: String?
    var id: String { key }

    static let all: [LabPreset] = [
${rows}
    ]

    static let byKey: [String: LabPreset] = Dictionary(uniqueKeysWithValues: all.map { ($0.key, $0) })
    static var panels: [String] { var seen = Set<String>(); return all.map(\\.panel).filter { seen.insert($0).inserted } }
}
`;
writeFileSync(new URL("../ios/Sentience/Models/LabPresets.swift", import.meta.url), out);
console.log(`wrote ${LAB_TESTS.length} presets`);
